export const genericBackendErrorLabels = new Set([
  'Bad Request',
  'Conflict',
  'Unauthorized',
  'Forbidden',
  'Not Found',
  'Internal Server Error',
]);

export function translateBackendMessage(message?: string | null) {
  const normalized = message?.trim();
  if (!normalized) return '';
  return backendMessageTranslations[normalized] ?? normalized;
}
