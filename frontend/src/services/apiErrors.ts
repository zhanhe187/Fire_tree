export function friendlyApiError(path: string, status: number) {
  if (status === 401) return '用户名或密码错误';
  if (status === 403) return '当前账号没有访问该后台模块的权限。';
  if (status === 413) return '上传文件过大，请选择较小的图片后重试。';
  if (status === 404) return '请求的数据不存在或已被删除。';
  if (status === 405) return '请求方式不正确，请刷新页面后重试。';
  if (status === 500) return '后台服务暂时不可用，请确认服务已启动后重试。';
  return `接口暂时不可用，请稍后重试。（${status}）`;
}

